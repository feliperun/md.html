pub(super) fn lookup(ch: char) -> Option<u8> {
    let scalar = ch as u32;
    let index = ENTRIES
        .binary_search_by_key(&scalar, |entry| entry.0)
        .ok()?;
    Some(ENTRIES[index].1)
}

#[cfg(test)]
mod tests {
    use super::ENTRIES;

    #[test]
    fn table_is_sorted_unique_ascii_and_single_byte() {
        let mut previous = None;
        for (scalar, output) in ENTRIES {
            if let Some(previous) = previous {
                assert!(previous < *scalar, "entries out of order");
            }
            previous = Some(*scalar);
            assert!(
                output.is_ascii_lowercase()
                    || output.is_ascii_digit()
                    || *output == b'-'
                    || *output == b'_'
            );
        }
        assert_eq!(ENTRIES.len(), 488, "generator asserted exactly 488 entries");
        assert_eq!(previous, Some(0x212B), "last entry is the ANGSTROM SIGN");
    }
}
